"""Generate the MCP tool catalog page and the facts the docs site shows.

Runs the real `netra-mcp` over stdio (initialize + tools/list, with and
without NETRA_MCP_ALLOW_MUTATIONS) so the published numbers cannot drift from
the code. Writes:
  website/docs/reference/mcp-tools.md
  website/src/data/facts.generated.json
CI runs this and fails if either file changes (scripts/ci-site-facts.sh).
"""
import json
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def list_tools(binary, mutations):
    env = dict(os.environ, NETRA_URL="http://127.0.0.1:1", NETRA_API_KEY="x")
    env.pop("NETRA_MCP_ALLOW_MUTATIONS", None)
    if mutations:
        env["NETRA_MCP_ALLOW_MUTATIONS"] = "true"
    msgs = [
        {"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {"protocolVersion": "2025-06-18"}},
        {"jsonrpc": "2.0", "method": "notifications/initialized"},
        {"jsonrpc": "2.0", "id": 2, "method": "tools/list"},
        {"jsonrpc": "2.0", "id": 3, "method": "prompts/list"},
        {"jsonrpc": "2.0", "id": 4, "method": "resources/list"},
    ]
    out = subprocess.run(
        [binary], input="\n".join(json.dumps(m) for m in msgs) + "\n",
        capture_output=True, text=True, env=env, timeout=60, check=True,
    ).stdout
    res = {r["id"]: r for r in map(json.loads, out.splitlines()) if "id" in r}
    return (
        res[1]["result"]["serverInfo"],
        res[2]["result"]["tools"],
        res[3]["result"].get("prompts", []),
        res[4]["result"].get("resources", []),
    )


def first_sentence(text):
    text = " ".join(text.split())
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    s = m.group(1) if m else text
    return s.replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")


def main():
    with tempfile.TemporaryDirectory() as tmp:
        binary = os.path.join(tmp, "netra-mcp")
        subprocess.run(["go", "build", "-trimpath", "-o", binary, "./cmd/netra-mcp"], cwd=ROOT, check=True)
        info, read_tools, prompts, resources = list_tools(binary, False)
        _, all_tools, _, _ = list_tools(binary, True)

    read_names = {t["name"] for t in read_tools}
    mutating = sorted((t for t in all_tools if t["name"] not in read_names), key=lambda t: t["name"])
    server = json.load(open(os.path.join(ROOT, "server.json")))

    groups = {}
    for t in sorted(read_tools, key=lambda t: t["name"]):
        parts = t["name"].split("_")
        groups.setdefault(parts[1] if len(parts) > 2 else "core", []).append(t)

    lines = [
        "---",
        'title: "MCP tool catalog"',
        "sidebar_position: 2",
        "---",
        "",
        "<!-- GENERATED by scripts/gen-site-facts.py from the netra-mcp binary. Do not edit. -->",
        "",
        f"`netra-mcp` {info['version']} registers **{len(all_tools)} tools**: "
        f"**{len(read_tools)} read-only** and **{len(mutating)} mutating**. "
        "The mutating tools are not even listed unless `NETRA_MCP_ALLOW_MUTATIONS=true` is set, "
        "and they keep the controller's own guards (plan token, risk confirmation, leases).",
        "",
        f"It also serves {len(prompts)} prompts and {len(resources)} resources. "
        "See [MCP integration](../integrations/mcp-integration.md) for setup.",
        "",
        "## Read-only tools",
        "",
    ]
    for g in sorted(groups):
        lines += [f"### {g}", "", "| Tool | What it does |", "|---|---|"]
        for t in groups[g]:
            lines.append(f"| `{t['name']}` | {first_sentence(t.get('description', ''))} |")
        lines.append("")
    lines += [
        "## Mutating tools (opt in)",
        "",
        "Listed only when `NETRA_MCP_ALLOW_MUTATIONS=true`. Each call is attributed to `NETRA_MCP_ACTOR`.",
        "",
        "| Tool | What it does |",
        "|---|---|",
    ]
    for t in mutating:
        lines.append(f"| `{t['name']}` | {first_sentence(t.get('description', ''))} |")
    lines.append("")

    ref = os.path.join(ROOT, "website", "docs", "reference")
    os.makedirs(ref, exist_ok=True)
    open(os.path.join(ref, "mcp-tools.md"), "w").write("\n".join(lines))

    docs_md = sum(1 for r, _, fs in os.walk(os.path.join(ROOT, "docs")) for f in fs if f.endswith(".md"))
    facts = {
        "version": server["version"],
        "mcpName": server["name"],
        "mcpImage": server["packages"][0]["identifier"],
        "mcpTools": len(all_tools),
        "mcpReadTools": len(read_tools),
        "mcpMutatingTools": len(mutating),
        "mcpPrompts": len(prompts),
        "mcpResources": len(resources),
        "docPages": docs_md,
    }
    os.makedirs(os.path.join(ROOT, "website", "src", "data"), exist_ok=True)
    open(os.path.join(ROOT, "website", "src", "data", "facts.generated.json"), "w").write(
        json.dumps(facts, indent=2) + "\n"
    )
    print("site facts:", json.dumps(facts))


if __name__ == "__main__":
    sys.exit(main())
